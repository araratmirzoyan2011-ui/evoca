const SeedLoanDetails = () => {
  const [log, setLog] = useState([]);
  const [running, setRunning] = useState(false);

  const handleSeed = async () => {
    setRunning(true);
    const lines = [];

    try {
      const snap = await getDocs(collection(db, "loans"));

      for (const d of snap.docs) {
        const { id, title } = d.data();

        const payload = {};
const details = loanDetailsById[id];
const conditions = loanConditionsById[id];
const documents = loanDocumentsById[id];

if (details?.length) payload.details = details;
if (conditions?.length) payload.conditions = conditions;
if (documents?.length) payload.documents = documents;

        if (Object.keys(payload).length > 0) {
          await updateDoc(doc(db, "loans", d.id), payload);
          lines.push(
            `✅ ${id} — ${title} [${Object.keys(payload).join(", ")}]`
          );
        } else {
          lines.push(`⚠️ ${id} — ${title}: ոչինչ չկա, բաց թողնվեց`);
        }
      }
    } catch (e) {
      console.error(e);
      lines.push("❌ Սխալ, տես console-ը");
    }

    setLog(lines);
    setRunning(false);
  };

  return (
    <div className="container mx-auto px-4 py-6">
      <button
        onClick={handleSeed}
        disabled={running}
        className="rounded-xl bg-purple-700 px-6 py-3 font-semibold text-white disabled:opacity-50"
      >
        {running ? "Գրվում է..." : "Գրել details + conditions Firestore"}
      </button>

      <ul className="mt-4 space-y-1 text-sm">
        {log.map((line, i) => (
          <li key={i}>{line}</li>
        ))}
      </ul>
    </div>
  );
};
export default SeedLoanDetails;