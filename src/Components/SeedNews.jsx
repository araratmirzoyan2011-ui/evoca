const pick = (arr, k) => arr[k % arr.length];

const fmt = (d) =>
  `${String(d.getDate()).padStart(2, "0")}.${String(d.getMonth() + 1).padStart(
    2,
    "0"
  )}.${d.getFullYear()}`;

const makeContent = (k, lead) => {
  const start = (k * 3) % POINTS.length;
  return [
    lead,
    `${pick(BODY_A, k)} ${pick(BODY_B, k)}`,
    `## ${pick(HEADINGS, k)}`,
    `- ${pick(POINTS, start)}`,
    `- ${pick(POINTS, start + 1)}`,
    `- ${pick(POINTS, start + 2)}`,
    `*${pick(CLOSINGS, k)}*`,
  ].join("\n");
};

// i = 0 -> ամենաթարմը։ Բաշխումը՝ 1 հատ newsFeatured, 6 հատ newsBottom, մնացածը՝ news
const buildItems = () => {
  const counters = { news: 0, newsFeatured: 0, newsBottom: 0 };
  const used = {};

  return Array.from({ length: TOTAL }, (_, i) => {
    const n = i + 1;
    const col =
      i === 4 ? "newsFeatured" : i >= 10 && i < 16 ? "newsBottom" : "news";
    const category = PATTERN[i % PATTERN.length];

    const idx = used[category] ?? 0;
    used[category] = idx + 1;
    const pool = ITEMS[category];
    const [title, lead] = pool[idx % pool.length];

    return {
      col,
      id: `sample-${String(n).padStart(3, "0")}`,
      data: {
        category,
        title,
        description: lead,
        content: makeContent(i, lead),
        date: fmt(new Date(2026, 9, 30 - i * 7)), // dd.mm.yyyy, յուրաքանչյուրը 1 շաբաթ հին
        image: `https://picsum.photos/seed/sample-${n}/650/463`,
        order: counters[col]++,
      },
    };
  });
};

export async function seedNews() {
  const batch = writeBatch(db);
  buildItems().forEach(({ col, id, data }) => batch.set(doc(db, col, id), data));
  await batch.commit();
  console.log(`Ավելացվեց ${TOTAL} փորձնական նորություն`);
}

// Ջնջում է միայն sample-NNN id-ով փաստաթղթերը
export async function removeSeedNews() {
  const batch = writeBatch(db);
  buildItems().forEach(({ col, id }) => batch.delete(doc(db, col, id)));
  await batch.commit();
  console.log("Փորձնական նորությունները ջնջվեցին");
}