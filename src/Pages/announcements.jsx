// "19.10.2026" -> "2026-10-19" (համեմատելու համար <input type="date">-ի հետ)
const toISO = (d) => {
  const [dd, mm, yyyy] = d.split(".");
  return `${yyyy}-${mm}-${dd}`;
};

const chunk = (arr, size) =>
  Array.from({ length: Math.ceil(arr.length / size) }, (_, i) =>
    arr.slice(i * size, i * size + size)
  );

const Announcements = () => {
  const [from, setFrom] = useState("");
  const [to, setTo] = useState("");
  const [page, setPage] = useState(1);

  const isFiltering = Boolean(from || to);

  const pages = useMemo(() => {
    if (!isFiltering) return announcementsPages;

    // Ֆիլտրի դեպքում՝ բոլոր էջերի տվյալները միասին, նորից 6-ական
    const filtered = announcementsPages.flat().filter((a) => {
      const iso = toISO(a.date);
      if (from && iso < from) return false;
      if (to && iso > to) return false;
      return true;
    });
    return chunk(filtered, ITEMS_PER_PAGE);
  }, [from, to, isFiltering]);

  const totalPages = Math.max(1, pages.length);
  const currentItems = pages[page - 1] || [];

  const goTo = (p) => {
    if (p >= 1 && p <= totalPages) {
      setPage(p);
      window.scrollTo({ top: 0, behavior: "smooth" });
    }
  };

  return (
    <>
      <Header />

      <main className="bg-[#f3f2fa] min-h-screen">
        <div className="max-w-6xl mx-auto px-4 pt-10">
          {/* Title + date filter */}
          <div className="flex flex-col md:flex-row md:items-center md:justify-between gap-4">
            <h1 className="text-3xl md:text-4xl font-extrabold text-gray-900">
              Հայտարարություններ
            </h1>

            <div className="flex items-center gap-3 text-xs text-gray-600">
              <svg
                className="w-6 h-6 text-gray-300"
                fill="none"
                stroke="currentColor"
                viewBox="0 0 24 24"
              >
                <path
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  strokeWidth="1.5"
                  d="M8 7V3m8 4V3M4 11h16M5 5h14a1 1 0 011 1v14a1 1 0 01-1 1H5a1 1 0 01-1-1V6a1 1 0 011-1z"
                />
              </svg>
              <input
                type="date"
                aria-label="Սկսած"
                value={from}
                onChange={(e) => {
                  setFrom(e.target.value);
                  setPage(1);
                }}
                className="bg-transparent border-b border-gray-300 px-2 py-1 focus:outline-none focus:border-purple-700"
              />
              <span>-</span>
              <input
                type="date"
                aria-label="Մինչև"
                value={to}
                onChange={(e) => {
                  setTo(e.target.value);
                  setPage(1);
                }}
                className="bg-transparent border-b border-gray-300 px-2 py-1 focus:outline-none focus:border-purple-700"
              />
            </div>
          </div>

          {/* Content */}
          <div className="relative mt-10 pb-20">
            {/* Illustration (փոխիր քո նկարի ճանապարհով) */}
            <img
              src="/images/announcements-clipboard.png"
              alt=""
              className="hidden lg:block absolute left-0 top-10 w-72 pointer-events-none select-none"
            />

            <div className="lg:ml-[36%] flex flex-col gap-5">
              {currentItems.length === 0 && (
                <p className="text-gray-500 text-center py-10">
                  Հայտարարություններ չեն գտնվել
                </p>
              )}

              {currentItems.map((a) => (
                <AccordionItem
                  key={a.id}
                  title={a.title}
                  date={a.date}
                  description={a.description}
                  items={a.items}
                />
              ))}

              {/* Pagination */}
              {totalPages > 1 && (
                <div className="flex items-center gap-6 mt-6 select-none">
                  <button
                    onClick={() => goTo(page - 1)}
                    disabled={page === 1}
                    className={`text-2xl ${
                      page === 1
                        ? "text-gray-300 cursor-default"
                        : "text-purple-700 cursor-pointer"
                    }`}
                    aria-label="Նախորդ"
                  >
                    ←
                  </button>

                  {Array.from({ length: totalPages }, (_, i) => i + 1).map(
                    (p) => (
                      <button
                        key={p}
                        onClick={() => goTo(p)}
                        className={`w-9 h-9 rounded-full text-sm font-bold cursor-pointer transition-colors ${
                          p === page
                            ? "bg-purple-700 text-white"
                            : "text-gray-800 hover:text-purple-700"
                        }`}
                      >
                        {p}
                      </button>
                    )
                  )}

                  <button
                    onClick={() => goTo(page + 1)}
                    disabled={page === totalPages}
                    className={`text-2xl ${
                      page === totalPages
                        ? "text-gray-300 cursor-default"
                        : "text-purple-700 cursor-pointer"
                    }`}
                    aria-label="Հաջորդ"
                  >
                    →
                  </button>
                </div>
              )}
            </div>
          </div>
        </div>
      </main>

      <Footer />
    </>
  );
};

export default Announcements;