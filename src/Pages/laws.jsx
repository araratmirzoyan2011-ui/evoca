// url-ները դատարկ են, լրացրու իրական հղումներով (կամ ուղղակիորեն Firestore-ում)
const lawsData = lawsTitles.map((title, i) => ({
  id: String(i + 1),
  title,
  url: "#",
  order: i + 1,
}));

const regulationsData = regulationsTitles.map((title, i) => ({
  id: String(i + 1),
  title,
  url: "#",
  order: i + 1,
}));

// ---------- COMPONENT ----------
function Laws() {
  const [laws, setLaws] = useState([]);
  const [regulations, setRegulations] = useState([]);
  const [seeding, setSeeding] = useState(false);

  const fetchData = async () => {
    try {
      const lawsSnap = await getDocs(
        query(collection(db, "laws"), orderBy("order"))
      );
      setLaws(lawsSnap.docs.map((d) => ({ id: d.id, ...d.data() })));

      const regSnap = await getDocs(
        query(collection(db, "lawRegulations"), orderBy("order"))
      );
      setRegulations(regSnap.docs.map((d) => ({ id: d.id, ...d.data() })));
    } catch (err) {
      console.error("Laws fetch error:", err);
    }
  };

  useEffect(() => {
    fetchData();
  }, []);

  const seedData = async () => {
    setSeeding(true);
    try {
      for (const item of lawsData) {
        await setDoc(doc(db, "laws", item.id), {
          title: item.title,
          url: item.url,
          order: item.order,
        });
      }
      for (const item of regulationsData) {
        await setDoc(doc(db, "lawRegulations", item.id), {
          title: item.title,
          url: item.url,
          order: item.order,
        });
      }
      await fetchData();
      alert("Տվյալները հաջողությամբ ավելացվեցին Firestore");
    } catch (err) {
      console.error("Seed error:", err);
      alert("Սխալ seed անելիս");
    }
    setSeeding(false);
  };

  return (
    <>
      <Header />

      <main className="relative w-full bg-white">
        <div className="mx-auto flex max-w-[1240px] gap-8 px-4 py-10">
          {/* Social icons (ձախ կողմում) */}
          <aside className="hidden shrink-0 pt-[70px] md:block">
            <SocialIcons />
          </aside>

          {/* Content */}
          <section className="min-w-0 flex-1 md:pl-[40px]">
            <h1 className="mb-14 text-[32px] font-medium text-[#333]">
              Իրավական ակտեր
            </h1>

            {/* Seed button — օգտագործիր մեկ անգամ, հետո հանիր */}
            <button
              onClick={seedData}
              disabled={seeding}
              className="mb-6 rounded bg-[#6a00f4] px-4 py-2 text-sm text-white disabled:opacity-50"
            >
              {seeding ? "Ավելացվում է..." : "Seed Firestore"}
            </button>

            {/* Օրենքներ */}
            <h2 className="mb-3 text-[32px] font-medium text-[#333]">
              Օրենքներ
            </h2>
            <ul className="mb-10">
              {laws.map((item) => (
                <li key={item.id} className="leading-[23px]">
                  <a
                    href={item.url}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="text-[15px] text-[#6a00f4] underline hover:text-[#4a00b0]"
                  >
                    {item.title}
                  </a>
                </li>
              ))}
            </ul>

            {/* Կանոնակարգեր և այլ իրավական ակտեր */}
            <h2 className="mb-5 text-[32px] font-medium text-[#333]">
              Կանոնակարգեր և այլ իրավական ակտեր
            </h2>
            <ol className="list-decimal space-y-5 pl-10 marker:font-semibold marker:text-[#6a00f4]">
              {regulations.map((item) => (
                <li key={item.id} className="pl-1 leading-[23px]">
                  <a
                    href={item.url}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="text-[15px] font-semibold text-[#6a00f4] underline hover:text-[#4a00b0]"
                  >
                    {item.title}
                  </a>
                </li>
              ))}
            </ol>
          </section>
        </div>
      </main>

      <Footer />
    </>
  );
}

export default Laws;