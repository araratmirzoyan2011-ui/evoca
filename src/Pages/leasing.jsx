const menuItems = [
  { label: "Evoca Leasing", path: "/leasing" },
  { label: "Հատուկ առաջարկ", path: "/special-offer" },
];

const Leasing = () => {
  const [LeasingAccordionsData, setLeasingAccordionsData] = useState([]);
  const [loading, setLoading] = useState(true);
  const [seeding, setSeeding] = useState(false);

  const fetchData = async () => {
    setLoading(true);
    try {
      const q = query(collection(db, "leasingAccordions"), orderBy("order"));
      const snap = await getDocs(q);
      setLeasingAccordionsData(snap.docs.map((d) => ({ docId: d.id, ...d.data() })));
    } catch (err) {
      console.error("Leasing fetch error:", err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchData();
  }, []);

  const seedData = async () => {
    setSeeding(true);
    try {
      await Promise.all(
        leasingAccordionsData.map((item) =>
          setDoc(doc(db, "leasingAccordions", `leasing-${item.order}`), item)
        )
      );
      await fetchData();
    } catch (err) {
      console.error("Leasing seed error:", err);
    } finally {
      setSeeding(false);
    }
  };

  return (
    <>
      <Header />
      <Navbar items={menuItems} />

      <section className="w-full bg-white py-10 px-4 md:px-12">
        <div className="max-w-7xl mx-auto flex gap-6 md:gap-24">
          <div className="hidden md:block">
            <div className="sticky top-24">
              <SocialIcons />
            </div>
          </div>
        </div>

        <div className="max-w-7xl mx-auto mt-10">
          <div className="md:pl-[calc(3rem+6rem)] max-w-4xl md:max-w-none">
            <h2 className="text-2xl font-extrabold text-gray-900 uppercase mb-6">
              ԱՆՀՐԱԺԵՇՏ ՏԵՂԵԿԱՏՎՈՒԹՅՈՒՆ
            </h2>

            {loading ? (
              <p className="text-gray-500">Բեռնվում է...</p>
            ) : LeasingAccordionsData.length === 0 ? (
              <button
                onClick={seedData}
                disabled={seeding}
                className="rounded-lg bg-[#6a0dde] px-5 py-2 text-white disabled:opacity-60"
              >
                {seeding ? "Ավելացվում է..." : "Seed Firestore"}
              </button>
            ) : (
              <div className="max-w-4xl space-y-4">
                {LeasingAccordionsData.map((item) => (
                  <LeasingAccordion
                    key={item.docId}
                    title={item.title}
                    blocks={item.blocks}
                  />
                ))}
              </div>
            )}
          </div>
        </div>
      </section>
      <Footer />
    </>
  );
};

export default Leasing;